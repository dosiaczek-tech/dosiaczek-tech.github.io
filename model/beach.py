"""How steeply the beach of every spot rises out of the water, from the Polish LiDAR surface model (GUGiK NMPT):
writes surf-beach.js.

On a steep beach the waves that reach the shore dump onto the sand (a shorebreak) instead of spilling over a
wide surf zone; that throws people and boards. We measure the slope where the waves run up: along seven lines
across the beach, 20 m apart, the distance in which the ground rises from 0.3 m to 1.3 m above the sea surface
the scan saw, and keep the median of the lines. The app warns about a shorebreak when the waves at the spot are
big and long enough to dump on that slope (surf-model.js). The scan shows the beach on the day of the flight;
storms and seasons reshape it. Run once after adding or moving spots: python model/beach.py.
"""
from __future__ import annotations

import argparse
import concurrent.futures
import json
from pathlib import Path
import statistics
import subprocess

from shelter import clip, destination

ROOT = Path(__file__).resolve().parents[1]
HALF, SIZE = 300, 600            # a 600 m square at 1 m around the spot
LINES = (-60, -40, -20, 0, 20, 40, 60)   # metres along the beach between the lines across it
REACH = 290                      # metres along each line to both sides of the spot
SEA = 40                         # metres at the seaward end of a line that give the sea surface
WATER = 1.0                      # higher points at the seaward end are not the sea (a breakwater, a boat)
LOW, HIGH = .3, 1.3              # the run-up band above the sea surface
GROUND = 8                       # metres in a row above HIGH: the beach, not a wave crest, a stone or a pile
WALL = .2                        # steeper than 1:5: a seawall, riprap or a cliff foot, not a beach face; not counted
MINIMUM_LINES = 3


def heights(spot, cache):
    grid = clip(spot["lat"], spot["lon"], HALF, SIZE, cache)
    north = grid["south"] + grid["nrows"] * grid["dy"]

    def height(lat, lon):
        c, r = int((lon - grid["west"]) / grid["dx"]), int((north - lat) / grid["dy"])
        if 0 <= r < grid["nrows"] and 0 <= c < grid["ncols"]:
            return grid["values"][r * grid["ncols"] + c]
        return None
    return height


def line_slope(profile):
    """Slope of the beach face on one line of heights every metre, from the sea towards the land; None when the
    line does not start on the sea or crosses no beach (a harbour, a cliff, a wall)."""
    sea = [h for h in profile[:SEA] if h is not None and h < WATER]
    if len(sea) < SEA // 2:
        return None
    level = statistics.median(sea)
    low, high = level + LOW, level + HIGH
    # From the land side: the first ground that stays above the band, then back towards the sea to the waterline.
    # Waves, stones and piles in the water rarely stay that high for GROUND metres.
    top = next((i for i in range(len(profile) - GROUND) if all(h is not None and h >= high for h in profile[i:i + GROUND])), None)
    if top is None:
        return None
    start = top
    while start > 0 and profile[start - 1] is not None and profile[start - 1] >= low:
        start -= 1
    slope = (HIGH - LOW) / max(1, top - start)
    return None if slope > WALL else slope


def spot_beach(spot, cache):
    height = heights(spot, cache)
    slopes = []
    for offset in LINES:
        base = destination(spot["lat"], spot["lon"], spot["normal"] + 90, offset)
        profile = [height(*destination(*base, spot["normal"], d)) for d in range(REACH, -REACH - 1, -1)]
        slope = line_slope(profile)
        if slope is not None:
            slopes.append(slope)
    if len(slopes) < MINIMUM_LINES:
        return None
    return {"lat": spot["lat"], "lon": spot["lon"], "normal": spot["normal"], "slope": round(statistics.median(slopes), 3), "lines": len(slopes)}


def write(entries, path):
    body = ",\n".join(f'    {json.dumps(id)}: {json.dumps(entry, separators=(",", ":"))}' for id, entry in sorted(entries.items()))
    path.write_text(f"""/* How steeply the beach rises out of the water at the spots, generated by model/beach.py from the GUGiK LiDAR
 * surface model (NMPT). slope: rise over run between 0.3 m and 1.3 m above the sea surface, median of the lines
 * across the beach. Valid only for the listed spot position; a moved spot needs the script again.
 */
(function (root) {{
  "use strict";
  const beaches = {{
{body}
  }};
  if (typeof module !== "undefined") module.exports = beaches;
  else root.SurfBeach = beaches;
}})(typeof globalThis !== "undefined" ? globalThis : this);
""", encoding="utf-8")


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--cache", type=Path, default=ROOT / ".forecast-cache" / "beach")
    parser.add_argument("--output", type=Path, default=ROOT / "surf-beach.js")
    parser.add_argument("--spots", help="Comma-separated IDs; omitted means all")
    parser.add_argument("--workers", type=int, default=4)
    args = parser.parse_args()
    spots = json.loads(subprocess.check_output(["node", "-e", "console.log(JSON.stringify(require('./surf-spots.js')))"], cwd=ROOT, text=True))
    if args.spots:
        spots = [s for s in spots if s["id"] in set(args.spots.split(","))]
    entries = {}
    with concurrent.futures.ThreadPoolExecutor(max_workers=args.workers) as pool:
        futures = {pool.submit(spot_beach, s, args.cache): s for s in spots}
        for future in concurrent.futures.as_completed(futures):
            spot = futures[future]
            try:
                entry = future.result()
            except Exception as error:
                print(f'{spot["id"]}: FAILED {type(error).__name__}: {str(error)[:120]}', flush=True)
                continue
            if entry:
                entries[spot["id"]] = entry
                print(f'{spot["id"]}: nachylenie 1:{round(1 / entry["slope"]) if entry["slope"] else "∞"} ({entry["lines"]} linii)', flush=True)
            else:
                print(f'{spot["id"]}: brak plaży przy linii wody w skanie, pominięty', flush=True)
    if args.spots and args.output.exists():
        # A partial run keeps the other spots of the existing file and drops the measured ones that lost their beach.
        existing = json.loads(subprocess.check_output(["node", "-e", f"console.log(JSON.stringify(require({json.dumps(str(args.output))})))"], text=True))
        entries = {**{id: entry for id, entry in existing.items() if id not in {s["id"] for s in spots}}, **entries}
    write(entries, args.output)
    print(f"Saved {len(entries)} spots to {args.output}", flush=True)


if __name__ == "__main__":
    main()
